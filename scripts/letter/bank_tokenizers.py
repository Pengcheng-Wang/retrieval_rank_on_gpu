"""Preserve native RQ checkpoints on workers; only node0 writes durable bundles."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shlex
import shutil
import socket
import subprocess
import sys
import time
import uuid
from pathlib import Path

from bank import copy_artifact, source_manifest
from protocol import file_sha256, require_hash, write_json


def checkpoint_path(run: Path, value: str) -> Path:
    path = Path(value)
    if not path.is_absolute():
        path = run / path
    if (path.parent.resolve() != (run / "checkpoints").resolve()
            or not re.fullmatch(r"epoch-\d{5}", path.name) or path.is_symlink()):
        raise ValueError("Tokenizer checkpoint escapes its declared run")
    return path


def read_state(path: Path, config: dict) -> dict:
    import torch

    receipt = json.loads((path / "completed.json").read_text(encoding="utf-8"))
    if (receipt.get("status") != "complete" or receipt.get("kind") != "tokenizer_epoch_checkpoint"
            or receipt["epoch"] + 1 != int(path.name.split("-")[1])):
        raise ValueError("Invalid sealed tokenizer epoch receipt")
    require_hash(path / "state.pt", receipt["state_sha256"])
    # This is a checksummed checkpoint generated by this task, not downloaded weights.
    state = torch.load(path / "state.pt", map_location="cpu", weights_only=False)
    required = {"epoch", "spec", "model", "optimizer", "initted", "selected_checkpoint",
                "python_rng", "numpy_rng", "torch_rng", "cuda_rng",
                "best_loss", "best_collision_rate"}
    if (set(state) != required or state["epoch"] != receipt["epoch"] or state["spec"] != config
            or not state["initted"] or not all(state["initted"])):
        raise ValueError("Tokenizer state, specification or initialization mismatch")
    return state


def verify_bundle(path: Path) -> dict:
    receipt = json.loads((path / "completed.json").read_text(encoding="utf-8"))
    if receipt.get("status") != "complete" or receipt.get("kind") != "tokenizer_resume_bundle":
        raise ValueError("Not a sealed tokenizer bundle")
    actual = source_manifest(path / "payload")
    if actual != receipt["payload_manifest"]:
        raise ValueError("Tokenizer bundle payload checksum mismatch")
    return receipt


def snapshot(run: Path, staging: Path) -> dict | None:
    marker = run / "latest-state.json"
    if not marker.is_file():
        return None
    if run.is_symlink() or (run / "checkpoints").is_symlink():
        raise ValueError("Tokenizer run/checkpoints must not be redirected")
    completion = run / "completed.json"
    final_bytes = completion.read_bytes() if completion.is_file() else None
    final = json.loads(final_bytes) if final_bytes is not None else None
    config = json.loads((run / "run-config.json").read_text(encoding="utf-8"))
    if config.get("synthetic_fixture") is not False or not config.get("track_id"):
        raise ValueError("Only explicitly identified real tokenizer runs can be banked here")
    latest_bytes = marker.read_bytes()
    latest = json.loads(latest_bytes)
    last = checkpoint_path(run, latest["checkpoint"])
    state = read_state(last, config)
    if state["epoch"] + 1 != latest["epoch"]:
        raise ValueError("Tokenizer latest-state pointer differs from its sealed epoch")
    checkpoints = {last}
    selected = state["selected_checkpoint"]
    if selected is not None:
        best = checkpoint_path(run, selected)
        read_state(best, config)
        checkpoints.add(best)
    phase = "completed" if final else "checkpoint"
    if final:
        require_hash(run / "run-config.json", final["run_config_sha256"])
        if (final["status"] != "complete" or final["synthetic_fixture"] is not False
                or latest["epoch"] != config["epochs"] or selected != final["selected_checkpoint"]
                or final["track_id"] != config["track_id"]):
            raise ValueError("Incomplete or mismatched final tokenizer run")
        export = json.loads((run / "export/export.json").read_text())
        require_hash(run / "export/index.json", export["index_sha256"])
        if final["export"] != export:
            raise ValueError("Final tokenizer export receipt differs from its index")
    key = file_sha256(run / "run-config.json") + file_sha256(last / "completed.json")
    if final:
        key += file_sha256(completion)
    identity = f"{run.name}-{phase}-{hashlib.sha256(key.encode()).hexdigest()[:16]}"
    if not re.fullmatch(r"[A-Za-z0-9_.-]+", identity):
        raise ValueError("Invalid tokenizer bundle identity")
    destination = staging / identity
    if destination.exists():
        verify_bundle(destination)
    else:
        staging.mkdir(parents=True, exist_ok=True)
        partial = staging / f".partial-{identity}-{uuid.uuid4().hex}"
        payload = partial / "payload"
        payload.mkdir(parents=True)
        shutil.copyfile(run / "run-config.json", payload / "run-config.json")
        (payload / "latest-state.json").write_bytes(latest_bytes)
        for path in sorted(checkpoints):
            shutil.copytree(path, payload / "checkpoints" / path.name)
            read_state(payload / "checkpoints" / path.name, config)
        if final:
            (payload / "completed.json").write_bytes(final_bytes)
            shutil.copytree(run / "export", payload / "export")
        write_json(partial / "completed.json", {
            "status": "complete", "kind": "tokenizer_resume_bundle", "phase": phase,
            "source_run": str(run), "track_id": config["track_id"],
            "latest_checkpoint": f"checkpoints/{last.name}", "selected_checkpoint": selected,
            "run_completed_sha256": file_sha256(completion) if final else None,
            "payload_manifest": source_manifest(payload),
        })
        verify_bundle(partial)
        partial.rename(destination)
    return {"identity": identity, "path": str(destination), "phase": phase}


def acknowledge(run: Path, ack_root: Path, digest: str) -> None:
    require_hash(run / "completed.json", digest)
    receipt = json.loads((run / "completed.json").read_text())
    if receipt.get("status") != "complete" or receipt.get("synthetic_fixture") is not False:
        raise ValueError("Only a complete real tokenizer can receive a durable acknowledgment")
    write_json(ack_root / f"{run.name}.tokenizer.json", {
        "status": "banked", "completed_sha256": digest,
    })


def worker_snapshot(args, run: Path) -> dict | None:
    if args.source_host == "node-0":
        return snapshot(run, args.remote_staging)
    command = shlex.join([
        "env", "CUDA_VISIBLE_DEVICES=0", "bash", str(args.source_project / "scripts/letter/env.sh"),
        "python", str(args.source_project / "scripts/letter/bank_tokenizers.py"),
        "snapshot", "--run", str(run), "--staging", str(args.remote_staging),
    ])
    response = subprocess.run(
        ["ssh", "-n", "-o", "BatchMode=yes", "-o", "ConnectTimeout=20", args.source_host, command],
        check=True, capture_output=True, text=True, timeout=180,
    )
    if response.stderr:
        print(response.stderr.strip(), file=sys.stderr, flush=True)
    return json.loads(response.stdout)


def watch(args) -> None:
    import fcntl

    if (socket.gethostname() != "node-0" or args.writer_host != "node-0"
            or args.source_host not in {"node-0", "node-1", "node-2"}):
        raise RuntimeError("Tokenizer banking must use node0 and an explicitly assigned worker")
    banked = set()
    print(f"TOKENIZER_SINGLE_WRITER_READY {args.source_host}", flush=True)
    while True:
        all_complete = True
        for run in args.runs:
            artifact = worker_snapshot(args, run)
            if artifact is None:
                all_complete = False
                continue
            all_complete = all_complete and artifact["phase"] == "completed"
            identity, remote = artifact["identity"], Path(artifact["path"])
            if (not re.fullmatch(r"[A-Za-z0-9_.-]+", identity) or not identity.startswith(run.name + "-")
                    or remote.parent != args.remote_staging or remote.name != identity):
                raise ValueError("Tokenizer worker response escaped the declared snapshot root")
            if identity in banked:
                continue
            if args.source_host == "node-0":
                local = remote
            else:
                local = args.local_staging / args.source_host / identity
                local.mkdir(parents=True, exist_ok=True)
                subprocess.run(["rsync", "-a", "--quiet", f"{args.source_host}:{remote}/", f"{local}/"],
                               check=True, timeout=600)
            receipt = verify_bundle(local)
            args.lock_file.parent.mkdir(parents=True, exist_ok=True)
            with args.lock_file.open("a") as lock:
                fcntl.flock(lock, fcntl.LOCK_EX)
                copy_artifact(local, args.destination / identity)
            if artifact["phase"] == "completed":
                if args.source_host == "node-0":
                    acknowledge(run, args.ack_root, receipt["run_completed_sha256"])
                else:
                    command = shlex.join([
                        "python3", str(args.source_project / "scripts/letter/bank_tokenizers.py"), "ack",
                        "--run", str(run), "--ack-root", str(args.ack_root),
                        "--completed-sha256", receipt["run_completed_sha256"],
                    ])
                    subprocess.run(["ssh", "-n", "-o", "BatchMode=yes", args.source_host, command],
                                   check=True, timeout=60)
            banked.add(identity)
            print(f"BANKED_TOKENIZER {identity}", flush=True)
        if all_complete:
            print("ALL_TOKENIZERS_DURABLY_COMPLETE", flush=True)
            return
        if args.once:
            return
        time.sleep(args.interval)


def main() -> None:
    parser = argparse.ArgumentParser()
    commands = parser.add_subparsers(dest="command", required=True)
    snap = commands.add_parser("snapshot")
    snap.add_argument("--run", type=Path, required=True)
    snap.add_argument("--staging", type=Path, required=True)
    ack = commands.add_parser("ack")
    ack.add_argument("--run", type=Path, required=True)
    ack.add_argument("--ack-root", type=Path, required=True)
    ack.add_argument("--completed-sha256", required=True)
    watcher = commands.add_parser("watch")
    for name in ("source-host", "writer-host"):
        watcher.add_argument(f"--{name}", required=True)
    watcher.add_argument("--runs", type=Path, nargs="+", required=True)
    for name in ("source-project", "remote-staging", "local-staging", "destination", "lock-file", "ack-root"):
        watcher.add_argument(f"--{name}", type=Path, required=True)
    watcher.add_argument("--interval", type=int, default=600)
    watcher.add_argument("--once", action="store_true")
    args = parser.parse_args()
    if args.command == "snapshot":
        print(json.dumps(snapshot(args.run, args.staging)))
    elif args.command == "ack":
        acknowledge(args.run, args.ack_root, args.completed_sha256)
    else:
        if args.interval < 30 or len(set(args.runs)) != len(args.runs):
            parser.error("Use an interval of at least30seconds and distinct tokenizer runs")
        watch(args)


if __name__ == "__main__":
    main()
